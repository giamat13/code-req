// Writes public/js/firebase-config.js from FIREBASE_* environment variables and
// fills the __SITE_URL__ placeholder used by sitemap, robots, and Open Graph tags.
// Without variables the file keeps placeholder values, which the app reports as "not configured".

import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const publicDir = fileURLToPath(new URL("../public/", import.meta.url));
const configFile = join(publicDir, "js", "firebase-config.js");

const CONFIG_KEYS = [
  ["apiKey", "FIREBASE_API_KEY"],
  ["authDomain", "FIREBASE_AUTH_DOMAIN"],
  ["projectId", "FIREBASE_PROJECT_ID"],
  ["storageBucket", "FIREBASE_STORAGE_BUCKET"],
  ["messagingSenderId", "FIREBASE_MESSAGING_SENDER_ID"],
  ["appId", "FIREBASE_APP_ID"],
];

const SITE_PLACEHOLDER = "__SITE_URL__";
const SITE_FILE_EXTENSIONS = new Set([".html", ".xml", ".txt", ".webmanifest"]);

function envValue(name) {
  return process.env[name]?.trim() ?? "";
}

function configValue(envName) {
  return envValue(envName) || `REPLACE_WITH_${envName.replace(/^FIREBASE_/, "")}`;
}

function renderConfig() {
  const lines = CONFIG_KEYS.map(
    ([key, envName]) => `  ${key}: ${JSON.stringify(configValue(envName))},`,
  );
  return `// Generated by scripts/write-config.mjs. Run \`npm run config\` after changing the FIREBASE_* variables,
// or edit the values below for a local deployment. Web config values identify a project. They are not
// secrets, but every deployment should use its own project.

export const firebaseConfig = {
${lines.join("\n")}
};

// Used on localhost, where the Emulator Suite replaces the real project.
export const emulatorConfig = {
  host: "127.0.0.1",
  authUrl: "http://127.0.0.1:9099",
  firestorePort: 8080,
  projectId: "demo-apprequest",
};
`;
}

async function listFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(dir, entry.name);
      return entry.isDirectory() ? listFiles(path) : [path];
    }),
  );
  return nested.flat();
}

async function fillSiteUrl(siteUrl) {
  const files = (await listFiles(publicDir)).filter((file) =>
    SITE_FILE_EXTENSIONS.has(extname(file)),
  );
  let changed = 0;
  for (const file of files) {
    const text = await readFile(file, "utf8");
    if (!text.includes(SITE_PLACEHOLDER)) continue;
    await writeFile(file, text.replaceAll(SITE_PLACEHOLDER, siteUrl));
    changed += 1;
  }
  return changed;
}

await writeFile(configFile, renderConfig());
console.log(
  envValue("FIREBASE_PROJECT_ID")
    ? "Wrote public/js/firebase-config.js from FIREBASE_* variables."
    : "Wrote public/js/firebase-config.js with placeholders (FIREBASE_PROJECT_ID is not set).",
);

const siteUrl = envValue("SITE_URL");
if (siteUrl) {
  const normalized = siteUrl.endsWith("/") ? siteUrl : `${siteUrl}/`;
  const changed = await fillSiteUrl(normalized);
  console.log(`Filled the site URL in ${changed} file(s).`);
}
